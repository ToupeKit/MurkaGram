    // Возвращает примерную дату регистрации в unix-секундах
    public static long estimate(long userId) {
        final long[] first = ANCHORS[0];
        if (userId <= first[0]) {
            return first[1];
        }
        for (int i = 1; i < ANCHORS.length; i++) {
            final long[] a = ANCHORS[i - 1];
            final long[] b = ANCHORS[i];
            if (userId <= b[0]) {
                return interpolate(a, b, userId);
            }
        }
        // Выше последней точки — экстраполяция по последнему отрезку, но не позже «сейчас»
        final long[] a = ANCHORS[ANCHORS.length - 2];
        final long[] b = ANCHORS[ANCHORS.length - 1];
        final long now = System.currentTimeMillis() / 1000L;
        return Math.max(b[1], Math.min(interpolate(a, b, userId), now));
    }

    private static long interpolate(long[] a, long[] b, long id) {
        return a[1] + (long) ((double) (id - a[0]) * (b[1] - a[1]) / (b[0] - a[0]));
    }
