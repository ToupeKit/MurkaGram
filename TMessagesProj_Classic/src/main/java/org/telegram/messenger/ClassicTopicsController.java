public final class ClassicTopicsController {

    private ClassicTopicsController() {
    }

    // MurkaGram: dual UI, core-13 TopicsController.pinTopic
    public static void pinTopic(TopicsController self, long chatId, int topicId, boolean pin, BaseFragment fragment) {
        TL_forum.TL_messages_updatePinnedForumTopic req = new TL_forum.TL_messages_updatePinnedForumTopic();
        req.peer = self.getMessagesController().getInputPeer(-chatId);
        req.topic_id = topicId;
        req.pinned = pin;

        ArrayList<Integer> prevOrder = self.getCurrentPinnedOrder(chatId);
        ArrayList<Integer> newOrder = new ArrayList<>(prevOrder);
        newOrder.remove((Integer) topicId);
        if (pin) {
            newOrder.add(0, topicId);
        }
        self.applyPinnedOrder(chatId, newOrder);

        ConnectionsManager.getInstance(self.currentAccount).sendRequest(req, (response, error) -> {
            if (error != null) {
                if ("PINNED_TOO_MUCH".equals(error.text)) {
                    if (fragment == null) {
                        return;
                    }
                    self.applyPinnedOrder(chatId, prevOrder);
                    AndroidUtilities.runOnUIThread(() -> {
                        fragment.showDialog(
                            new AlertDialog.Builder(fragment.getContext())
                                .setTitle(LocaleController.getString(R.string.LimitReached))
                                .setMessage(LocaleController.formatString(R.string.LimitReachedPinnedTopics, MessagesController.getInstance(self.currentAccount).topicsPinnedLimit))
                                .setPositiveButton(LocaleController.getString(R.string.OK), null)
                                .create()
                        );
                    });
                } else if ("PINNED_TOPIC_NOT_MODIFIED".equals(error.text)) {
                    self.reloadTopics(chatId, false);
                }
            }
        });
    }

}
