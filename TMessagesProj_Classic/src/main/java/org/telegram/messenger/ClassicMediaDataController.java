    // MurkaGram: dual UI, core-13 MediaDataController.toggleStickerSet
    public static void toggleStickerSet(MediaDataController self, Context context, TLObject stickerSetObject, TLRPC.Document sticker, int toggle, BaseFragment baseFragment, FrameLayout bulletinContainer, boolean showSettings, boolean showTooltip, Runnable onUndo, boolean forget) {
        TLRPC.StickerSet stickerSet;
        TLRPC.TL_messages_stickerSet messages_stickerSet;

        if (stickerSetObject instanceof TLRPC.TL_messages_stickerSet) {
            messages_stickerSet = ((TLRPC.TL_messages_stickerSet) stickerSetObject);
            stickerSet = messages_stickerSet.set;
        } else if (stickerSetObject instanceof TLRPC.StickerSetCovered) {
            stickerSet = ((TLRPC.StickerSetCovered) stickerSetObject).set;
            if (toggle != 2) {
                messages_stickerSet = self.stickerSetsById.get(stickerSet.id);
                if (messages_stickerSet == null) {
                    return;
                }
            } else {
                messages_stickerSet = null;
            }
        } else {
            throw new IllegalArgumentException("Invalid type of the given stickerSetObject: " + stickerSetObject.getClass());
        }

        int type1 = MediaDataController.TYPE_IMAGE;
        if (stickerSet.masks) {
            type1 = MediaDataController.TYPE_MASK;
        } else if (stickerSet.emojis) {
            type1 = MediaDataController.TYPE_EMOJIPACKS;
        }
        final int type = type1;

        stickerSet.archived = toggle == 1;

        int currentIndex = 0;
        for (int a = 0; a < self.stickerSets[type].size(); a++) {
            TLRPC.TL_messages_stickerSet set = self.stickerSets[type].get(a);
            if (set.set.id == stickerSet.id) {
                currentIndex = a;
                self.stickerSets[type].remove(a);
                if (toggle == 2) {
                    set.set.title = stickerSet.title;
                    self.stickerSets[type].add(0, set);
                } else if (forget) {
                    self.stickerSetsById.remove(set.set.id);
                    self.installedStickerSetsById.remove(set.set.id);
                    self.stickerSetsByName.remove(set.set.short_name);
                }
                break;
            }
        }

        self.loadHash[type] = self.calcStickersHash(self.stickerSets[type]);
        self.putStickersToCache(type, self.stickerSets[type], self.loadDate[type], self.loadHash[type]);

        if (toggle == 2) {
            if (!self.cancelRemovingStickerSet(stickerSet.id)) {
                toggleStickerSetInternal(self, context, toggle, baseFragment, bulletinContainer, showSettings, stickerSetObject, stickerSet, sticker, type, showTooltip);
            }
        } else if (!showTooltip || baseFragment == null) {
            toggleStickerSetInternal(self, context, toggle, baseFragment, bulletinContainer, showSettings, stickerSetObject, stickerSet, sticker, type, false);
        } else {
            StickerSetBulletinLayout bulletinLayout = new StickerSetBulletinLayout(context, stickerSetObject, toggle, sticker, baseFragment == null ? null : baseFragment.getResourceProvider());
            int finalCurrentIndex = currentIndex;
            boolean[] undoDone = new boolean[1];
            self.markSetUninstalling(stickerSet.id, true);
            Bulletin.UndoButton undoButton = new Bulletin.UndoButton(context, false).setUndoAction(() -> {
                if (undoDone[0]) {
                    return;
                }
                undoDone[0] = true;
                self.markSetUninstalling(stickerSet.id, false);
                stickerSet.archived = false;

                self.stickerSets[type].add(finalCurrentIndex, messages_stickerSet);
                self.stickerSetsById.put(stickerSet.id, messages_stickerSet);
                self.installedStickerSetsById.put(stickerSet.id, messages_stickerSet);
                if (stickerSet.short_name != null) {
                    self.stickerSetsByName.put(stickerSet.short_name.toLowerCase(), messages_stickerSet);
                }
                self.removingStickerSetsUndos.remove(stickerSet.id);

                self.loadHash[type] = self.calcStickersHash(self.stickerSets[type]);
                self.putStickersToCache(type, self.stickerSets[type], self.loadDate[type], self.loadHash[type]);
                if (onUndo != null) {
                    onUndo.run();
                }

                self.getNotificationCenter().postNotificationName(NotificationCenter.stickersDidLoad, type, true);
            }).setDelayedAction(() -> {
                if (undoDone[0]) {
                    return;
                }
                undoDone[0] = true;
                toggleStickerSetInternal(self, context, toggle, baseFragment, bulletinContainer, showSettings, stickerSetObject, stickerSet, sticker, type, false);
            });
            bulletinLayout.setButton(undoButton);
            self.removingStickerSetsUndos.put(stickerSet.id, undoButton::undo);
            if (bulletinContainer != null) {
                Bulletin.make(bulletinContainer, bulletinLayout, Bulletin.DURATION_LONG).show();
            } else {
                Bulletin.make(baseFragment, bulletinLayout, Bulletin.DURATION_LONG).show();
            }
        }

        self.getNotificationCenter().postNotificationName(NotificationCenter.stickersDidLoad, type, true);
    }

    // MurkaGram: dual UI, core-13 MediaDataController.toggleStickerSets
    public static void toggleStickerSets(MediaDataController self, ArrayList<TLRPC.StickerSet> stickerSetList, int type, int toggle, BaseFragment baseFragment, boolean showSettings) {
        int stickerSetListSize = stickerSetList.size();
        ArrayList<TLRPC.InputStickerSet> inputStickerSets = new ArrayList<>(stickerSetListSize);

        for (int i = 0; i < stickerSetListSize; i++) {
            TLRPC.StickerSet stickerSet = stickerSetList.get(i);
            TLRPC.InputStickerSet inputStickerSet = new TLRPC.TL_inputStickerSetID();
            inputStickerSet.access_hash = stickerSet.access_hash;
            inputStickerSet.id = stickerSet.id;
            inputStickerSets.add(inputStickerSet);
            if (toggle != 0) {
                stickerSet.archived = toggle == 1;
            }
            for (int a = 0, size = self.stickerSets[type].size(); a < size; a++) {
                TLRPC.TL_messages_stickerSet set = self.stickerSets[type].get(a);
                if (set.set.id == inputStickerSet.id) {
                    self.stickerSets[type].remove(a);
                    if (toggle == 2) {
                        self.stickerSets[type].add(0, set);
                    } else {
                        self.stickerSetsById.remove(set.set.id);
                        self.installedStickerSetsById.remove(set.set.id);
                        self.stickerSetsByName.remove(set.set.short_name);
                    }
                    break;
                }
            }
        }

        self.loadHash[type] = self.calcStickersHash(self.stickerSets[type]);
        self.putStickersToCache(type, self.stickerSets[type], self.loadDate[type], self.loadHash[type]);
        self.getNotificationCenter().postNotificationName(NotificationCenter.stickersDidLoad, type, true);

        TLRPC.TL_messages_toggleStickerSets req = new TLRPC.TL_messages_toggleStickerSets();
        req.stickersets = inputStickerSets;
        switch (toggle) {
            case 0:
                req.uninstall = true;
                break;
            case 1:
                req.archive = true;
                break;
            case 2:
                req.unarchive = true;
                break;
        }
        self.getConnectionsManager().sendRequest(req, (response, error) -> AndroidUtilities.runOnUIThread(() -> {
            if (toggle != 0) {
                if (response instanceof TLRPC.TL_messages_stickerSetInstallResultArchive) {
                    processStickerSetInstallResultArchive(self, baseFragment, showSettings, type, (TLRPC.TL_messages_stickerSetInstallResultArchive) response);
                }
                self.loadStickers(type, false, false, true);
            } else {
                self.loadStickers(type, false, true);
            }
        }));
    }

    // MurkaGram: dual UI, core-13 MediaDataController.processStickerSetInstallResultArchive
    public static void processStickerSetInstallResultArchive(MediaDataController self, BaseFragment baseFragment, boolean showSettings, int type, TLRPC.TL_messages_stickerSetInstallResultArchive response) {
        for (int i = 0, size = response.sets.size(); i < size; i++) {
            self.installedStickerSetsById.remove(response.sets.get(i).set.id);
        }
        self.loadArchivedStickersCount(type, false);
        self.getNotificationCenter().postNotificationName(NotificationCenter.needAddArchivedStickers, response.sets);
        if (baseFragment != null && baseFragment.getParentActivity() != null) {
            StickersArchiveAlert alert = new StickersArchiveAlert(baseFragment.getParentActivity(), showSettings ? baseFragment : null, response.sets);
            baseFragment.showDialog(alert.create());
        }
    }

    // MurkaGram: dual UI, core-13 MediaDataController.removeMultipleStickerSets
    public static void removeMultipleStickerSets(MediaDataController self, Context context, BaseFragment fragment, ArrayList<TLRPC.TL_messages_stickerSet> sets) {
        if (sets == null || sets.isEmpty()) {
            return;
        }
        TLRPC.TL_messages_stickerSet messages_stickerSet = sets.get(sets.size() - 1);
        if (messages_stickerSet == null) {
            return;
        }
//        TLRPC.StickerSet stickerSet = messages_stickerSet.set;

        int type1 = MediaDataController.TYPE_IMAGE;
        if (messages_stickerSet.set.masks) {
            type1 = MediaDataController.TYPE_MASK;
        } else if (messages_stickerSet.set.emojis) {
            type1 = MediaDataController.TYPE_EMOJIPACKS;
        }
        final int type = type1;

        for (int i = 0; i < sets.size(); ++i) {
            sets.get(i).set.archived = false;
        }

        final int[] currentIndexes = new int[sets.size()];
        for (int a = 0; a < self.stickerSets[type].size(); a++) {
            TLRPC.TL_messages_stickerSet set = self.stickerSets[type].get(a);
            for (int b = 0; b < sets.size(); ++b) {
                if (set.set.id == sets.get(b).set.id) {
                    currentIndexes[b] = a;
                    self.stickerSets[type].remove(a);
                    self.stickerSetsById.remove(set.set.id);
                    self.installedStickerSetsById.remove(set.set.id);
                    self.stickerSetsByName.remove(set.set.short_name);
                    break;
                }
            }
        }

        self.putStickersToCache(type, self.stickerSets[type], self.loadDate[type], self.loadHash[type] = self.calcStickersHash(self.stickerSets[type]));
        self.getNotificationCenter().postNotificationName(NotificationCenter.stickersDidLoad, type, true);

        for (int i = 0; i < sets.size(); ++i) {
            self.markSetUninstalling(sets.get(i).set.id, true);
        }
        StickerSetBulletinLayout bulletinLayout = new StickerSetBulletinLayout(context, messages_stickerSet, sets.size(), StickerSetBulletinLayout.TYPE_REMOVED, null, fragment.getResourceProvider());
        boolean[] undoDone = new boolean[1];
        Bulletin.UndoButton undoButton = new Bulletin.UndoButton(context, false).setUndoAction(() -> {
            if (undoDone[0]) {
                return;
            }
            undoDone[0] = true;

            for (int i = 0; i < sets.size(); ++i) {
                self.markSetUninstalling(sets.get(i).set.id, false);
                sets.get(i).set.archived = false;

                self.stickerSets[type].add(currentIndexes[i], sets.get(i));
                self.stickerSetsById.put(sets.get(i).set.id, sets.get(i));
                self.installedStickerSetsById.put(sets.get(i).set.id, sets.get(i));
                self.stickerSetsByName.put(sets.get(i).set.short_name, sets.get(i));
                self.removingStickerSetsUndos.remove(sets.get(i).set.id);
            }

            self.putStickersToCache(type, self.stickerSets[type], self.loadDate[type], self.loadHash[type] = self.calcStickersHash(self.stickerSets[type]));
            self.getNotificationCenter().postNotificationName(NotificationCenter.stickersDidLoad, type, true);
        }).setDelayedAction(() -> {
            if (undoDone[0]) {
                return;
            }
            undoDone[0] = true;
            for (int i = 0; i < sets.size(); ++i) {
                toggleStickerSetInternal(self, context, 0, fragment, null, true, sets.get(i), sets.get(i).set, null, type, false);
            }
        });
        bulletinLayout.setButton(undoButton);
        for (int i = 0; i < sets.size(); ++i) {
            self.removingStickerSetsUndos.put(sets.get(i).set.id, undoButton::undo);
        }
        Bulletin.make(fragment, bulletinLayout, Bulletin.DURATION_LONG).show();
    }

    // MurkaGram: dual UI, core-13 MediaDataController.setPlaceholderImage
    public static void setPlaceholderImage(MediaDataController self, BackupImageView imageView, String setName, String emoji, String filter) {
        final TLRPC.InputStickerSet inputStickerSet = new TLRPC.TL_inputStickerSetShortName();
        inputStickerSet.short_name = setName;
        MediaDataController.getInstance(self.currentAccount).getStickerSet(inputStickerSet, 0, false, set -> {
            if (set == null) return;
            TLRPC.Document document = null;
            final ArrayList<Emoji.EmojiSpanRange> emojis = Emoji.parseEmojis(emoji);
            for (int i = 0; i < emojis.size(); ++i) {
                emojis.get(i).code = Emoji.fixEmoji(emojis.get(i).code.toString());
            }
            for (int i = 0; i < set.documents.size(); ++i) {
                final TLRPC.Document d = set.documents.get(i);
                boolean containsEveryEmoji = true;
                for (final Emoji.EmojiSpanRange thisEmoji : emojis) {
                    boolean containsThisEmoji = false;
                    for (int j = 0; j < set.packs.size(); ++j) {
                        if (set.packs.get(j).documents.contains(d.id) && TextUtils.equals(Emoji.fixEmoji(set.packs.get(j).emoticon), thisEmoji.code)) {
                            containsThisEmoji = true;
                            break;
                        }
                    }
                    if (!containsThisEmoji) {
                        containsEveryEmoji = false;
                        break;
                    }
                }
                if (containsEveryEmoji) {
                    document = d;
                    break;
                }
            }
            if (document != null) {
                Drawable thumbDrawable = DocumentObject.getSvgThumb(document, Theme.key_windowBackgroundWhiteGrayIcon, 0.2f, 1f, null);
                imageView.setImage(ImageLocation.getForDocument(document), filter, thumbDrawable, 0, document);
                imageView.invalidate();
            }
        });
    }

    // MurkaGram: dual UI, core-13 MediaDataController.toggleStickerSetInternal
    public static void toggleStickerSetInternal(MediaDataController self, Context context, int toggle, BaseFragment baseFragment, FrameLayout bulletinContainer, boolean showSettings, TLObject stickerSetObject, TLRPC.StickerSet stickerSet, TLRPC.Document sticker, int type, boolean showTooltip) {
        TLRPC.TL_inputStickerSetID stickerSetID = new TLRPC.TL_inputStickerSetID();
        stickerSetID.access_hash = stickerSet.access_hash;
        stickerSetID.id = stickerSet.id;

        if (toggle != 0) {
            TLRPC.TL_messages_installStickerSet req = new TLRPC.TL_messages_installStickerSet();
            req.stickerset = stickerSetID;
            req.archived = toggle == 1;
            self.markSetInstalling(stickerSet.id, true);
            self.getConnectionsManager().sendRequest(req, (response, error) -> AndroidUtilities.runOnUIThread(() -> {
                self.removingStickerSetsUndos.remove(stickerSet.id);
                if (response instanceof TLRPC.TL_messages_stickerSetInstallResultArchive) {
                    processStickerSetInstallResultArchive(self, baseFragment, showSettings, type, (TLRPC.TL_messages_stickerSetInstallResultArchive) response);
                }
                self.loadStickers(type, false, false, true, p -> {
                    self.markSetInstalling(stickerSet.id, false);
                });
                if (error == null && showTooltip) {
                    if (bulletinContainer != null) {
                        Bulletin.make(bulletinContainer, new StickerSetBulletinLayout(context, stickerSetObject, StickerSetBulletinLayout.TYPE_ADDED, sticker, baseFragment.getResourceProvider()), Bulletin.DURATION_SHORT).show();
                    } else if (baseFragment != null) {
                        Bulletin.make(baseFragment, new StickerSetBulletinLayout(context, stickerSetObject, StickerSetBulletinLayout.TYPE_ADDED, sticker, baseFragment.getResourceProvider()), Bulletin.DURATION_SHORT).show();
                    }
                }
            }));
        } else {
            self.markSetUninstalling(stickerSet.id, true);
            TLRPC.TL_messages_uninstallStickerSet req = new TLRPC.TL_messages_uninstallStickerSet();
            req.stickerset = stickerSetID;
            self.getConnectionsManager().sendRequest(req, (response, error) -> AndroidUtilities.runOnUIThread(() -> {
                self.removingStickerSetsUndos.remove(stickerSet.id);
                self.loadStickers(type, false, true, false, p -> {
                    self.markSetUninstalling(stickerSet.id, false);
                });
            }));
        }
    }

