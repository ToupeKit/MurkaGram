public final class ClassicContactsController {

    private ClassicContactsController() {
    }

    // MurkaGram: dual UI, core-13 ContactsController.deleteContactsUndoable
    public static void deleteContactsUndoable(ContactsController self, Context context, BaseFragment fragment, final ArrayList<TLRPC.User> users) {
        if (users == null || users.isEmpty()) {
            return;
        }

        HashMap<TLRPC.User, TLRPC.TL_contact> deletedContacts = new HashMap<>();

        for (int i = 0, N = users.size(); i < N; i++) {
            TLRPC.User user = users.get(i);
            TLRPC.TL_contact contact = self.contactsDict.get(user.id);

            user.contact = false;
            self.contacts.remove(contact);
            self.contactsDict.remove(user.id);

            deletedContacts.put(user, contact);
        }
        self.buildContactsSectionsArrays(false);
        self.getNotificationCenter().postNotificationName(NotificationCenter.updateInterfaces, MessagesController.UPDATE_MASK_NAME);
        self.getNotificationCenter().postNotificationName(NotificationCenter.contactsDidLoad);

        Bulletin.SimpleLayout layout = new Bulletin.SimpleLayout(context, fragment.getResourceProvider());
        layout.setTimer();
        layout.textView.setText(LocaleController.formatPluralString("ContactsDeletedUndo", deletedContacts.size()));
        Bulletin.UndoButton undoButton = new Bulletin.UndoButton(context, true, true, fragment.getResourceProvider());
        undoButton.setUndoAction(() -> {
            for (HashMap.Entry<TLRPC.User, TLRPC.TL_contact> entry : deletedContacts.entrySet()) {
                TLRPC.User user = entry.getKey();
                TLRPC.TL_contact contact = entry.getValue();

                user.contact = true;
                self.contacts.add(contact);
                self.contactsDict.put(user.id, contact);
            }
            self.buildContactsSectionsArrays(true);
            self.getNotificationCenter().postNotificationName(NotificationCenter.updateInterfaces, MessagesController.UPDATE_MASK_NAME);
            self.getNotificationCenter().postNotificationName(NotificationCenter.contactsDidLoad);
        });
        undoButton.setDelayedAction(() -> {
            self.deleteContact(users, false);
        });
        layout.setButton(undoButton);
        Bulletin bulletin = Bulletin.make(fragment, layout, Bulletin.DURATION_PROLONG);
        bulletin.show();
    }

}
